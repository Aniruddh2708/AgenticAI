"""Strict daily NSE bhavcopy acquisition/import; raw prices, never adjustments.

Format validation and an HTTPS origin are evidence, not a source-rights grant,
independent reconciliation, complete calendar, or corporate-action verification.
"""
import csv
from datetime import date, datetime, timezone
from decimal import Decimal, InvalidOperation
import hashlib
import io
import json
import math
from pathlib import Path, PurePosixPath
import re
import stat
import zipfile

import httpx

from vibefinance.config import TICKERS


MAX_ARTIFACT_BYTES = 32 * 1024 * 1024
MAX_CSV_BYTES = 64 * 1024 * 1024
MAX_ZIP_RATIO = 100
SPENT_DATA_END = date(2025, 12, 31)
MONTHS = ("JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC")
FORMATS = {
    "legacy": {"symbol": "SYMBOL", "series": "SERIES", "date": "TIMESTAMP",
               "open": "OPEN", "high": "HIGH", "low": "LOW", "close": "CLOSE", "volume": "TOTTRDQTY", "isin": "ISIN"},
    "udiff": {"symbol": "TckrSymb", "series": "SctySrs", "date": "TradDt",
              "open": "OpnPric", "high": "HghPric", "low": "LwPric", "close": "ClsPric", "volume": "TtlTradgVol", "isin": "ISIN"},
}


class ExchangeDataError(ValueError):
    def __init__(self, code, message):
        super().__init__(message)
        self.code = code


def _require(condition, code, message):
    if not condition:
        raise ExchangeDataError(code, message)


def _day(value):
    _require(isinstance(value, str) and re.fullmatch(r"\d{4}-\d{2}-\d{2}", value),
             "invalid_date", "Declare date as YYYY-MM-DD")
    try:
        day = date.fromisoformat(value)
    except ValueError as exc:
        raise ExchangeDataError("invalid_date", "Invalid calendar date") from exc
    _require(day <= date.today(), "future_date", "Cannot acquire a future session")
    return day


def archive_url(day, provider_format):
    """Canonical official daily URL; format choice is explicit, no fallbacks."""
    day = _day(day)
    _require(provider_format in FORMATS, "unknown_format", "Choose legacy or udiff")
    if provider_format == "legacy":
        month = MONTHS[day.month - 1]
        return (f"https://nsearchives.nseindia.com/content/historical/EQUITIES/{day.year}/{month}/"
                f"cm{day.day:02}{month}{day.year}bhav.csv.zip")
    return ("https://nsearchives.nseindia.com/content/cm/"
            f"BhavCopy_NSE_CM_0_0_0_{day:%Y%m%d}_F_0000.csv.zip")


def automation_permission(review_path, day):
    """Check a separately supplied operator declaration, not legal authenticity.

    Public viewing/downloading permission is not inferred to grant automation.
    No approval record or permission document is generated by this tool.
    """
    _require(review_path is not None, "permission_required", "Automated NSE fetching requires a local reviewed automation-permission record; use authorized local import otherwise")
    path = Path(review_path)
    try:
        _require(path.stat().st_size <= 1024 * 1024, "permission_required", "Permission review is oversized")
        raw = path.read_bytes()
        review = json.loads(raw)
        _require(isinstance(review, dict) and review.get("schema_version") == 1 and
                 review.get("kind") == "nse_automation_permission_review" and
                 review.get("status") == "reviewed_approved" and review.get("automation_authorized") is True,
                 "permission_required", "Review must explicitly approve NSE automated acquisition")
        _require(isinstance(review.get("reviewed_by"), str) and review["reviewed_by"].strip() and
                 isinstance(review.get("authorization_reference"), str) and review["authorization_reference"].strip(),
                 "permission_required", "Actual operator identity and permission reference are required")
        reviewed_at = datetime.fromisoformat(review["reviewed_at"])
        _require(reviewed_at.tzinfo is not None and reviewed_at <= datetime.now(timezone.utc),
                 "permission_required", "Permission review needs a completed timezone-aware timestamp")
        _require(review.get("source_host") == "nsearchives.nseindia.com" and
                 isinstance(review.get("authorized_dates"), list) and day in review["authorized_dates"] and
                 all(isinstance(value, str) and re.fullmatch(r"\d{4}-\d{2}-\d{2}", value) for value in review["authorized_dates"]),
                 "permission_required", "Permission must cover the exact requested date and official NSE archive host")
        evidence = review.get("evidence", {})
        name = evidence.get("path")
        _require(isinstance(name, str) and name and not Path(name).is_absolute() and ".." not in Path(name).parts,
                 "permission_required", "Permission artifact must have a local path inside the review directory")
        artifact = (path.resolve().parent / name).resolve()
        _require(artifact.is_relative_to(path.resolve().parent) and artifact.is_file() and
                 0 < artifact.stat().st_size <= MAX_ARTIFACT_BYTES,
                 "permission_required", "Actual permission artifact must exist within the reviewed directory")
        digest = evidence.get("sha256")
        _require(isinstance(digest, str) and re.fullmatch(r"[0-9a-f]{64}", digest) and
                 hashlib.sha256(artifact.read_bytes()).hexdigest() == digest,
                 "permission_required", "Permission artifact requires its matching SHA-256")
    except ExchangeDataError:
        raise
    except (OSError, ValueError, TypeError, KeyError, AttributeError) as exc:
        raise ExchangeDataError("permission_required", "Automation permission review is unavailable or invalid") from exc
    return {"review_manifest_sha256": hashlib.sha256(raw).hexdigest(),
            "permission_artifact_sha256": digest, "source_host": review["source_host"],
            "authorized_date": day, "reviewed_at": review["reviewed_at"],
            "verification_limit": "Operator declaration and file identity only; no legal authenticity certification"}


def fetch_spent_archive(day, provider_format, permission_review_path=None):
    """One normal TLS/proxy request for a spent/development date only.

    No retry, redirect, alternate mirror, TLS bypass, or fresh-outcome fetch.
    Calling this after a policy denial requires a meaningful access change.
    """
    _require(_day(day) <= SPENT_DATA_END, "unregistered_outcome", "Fetch is limited to spent/development dates through 2025-12-31")
    automation_permission(permission_review_path, day)
    url = archive_url(day, provider_format)
    chunks, size = [], 0
    with httpx.Client(timeout=30, follow_redirects=False) as client:
        with client.stream("GET", url) as response:
            response.raise_for_status()
            for chunk in response.iter_bytes():
                size += len(chunk)
                _require(size <= MAX_ARTIFACT_BYTES, "artifact_too_large", "Exchange artifact exceeds size bound")
                chunks.append(chunk)
    return b"".join(chunks), url


def _csv_payload(content, kind):
    _require(0 < len(content) <= MAX_ARTIFACT_BYTES, "artifact_too_large", "Empty or oversized source artifact")
    if kind == "csv":
        return content, None
    _require(kind == "zip", "unsupported_format", "Import one CSV or ZIP artifact")
    try:
        with zipfile.ZipFile(io.BytesIO(content)) as archive:
            members = archive.infolist()
            _require(len(members) == 1, "zip_members", "ZIP must contain exactly one CSV file")
            member = members[0]
            name = member.filename
            path = PurePosixPath(name)
            _require(not path.is_absolute() and len(path.parts) == 1 and name not in {".", ".."} and
                     "\\" not in name and ":" not in name and path.suffix.lower() == ".csv" and not member.is_dir(),
                     "unsafe_zip_path", "ZIP member must be a local CSV basename")
            _require(not stat.S_ISLNK(member.external_attr >> 16) and not (member.flag_bits & 1),
                     "unsafe_zip_member", "ZIP links and encrypted members are unsupported")
            _require(0 < member.file_size <= MAX_CSV_BYTES and
                     member.file_size <= max(1, member.compress_size) * MAX_ZIP_RATIO,
                     "zip_expansion", "ZIP uncompressed size or compression ratio exceeds bound")
            payload = archive.read(member)
            _require(len(payload) == member.file_size, "zip_size", "ZIP member size mismatch")
            return payload, name
    except (zipfile.BadZipFile, RuntimeError, NotImplementedError) as exc:
        raise ExchangeDataError("invalid_zip", "Invalid or unsupported ZIP artifact") from exc


def _session_date(value, provider_format):
    if provider_format == "udiff":
        return _day(value).isoformat()
    match = re.fullmatch(r"(\d{2})-([A-Z]{3})-(\d{4})", value)
    _require(match is not None and match.group(2) in MONTHS, "invalid_session_date", "Legacy TIMESTAMP must be DD-MMM-YYYY")
    try:
        return date(int(match.group(3)), MONTHS.index(match.group(2)) + 1, int(match.group(1))).isoformat()
    except ValueError as exc:
        raise ExchangeDataError("invalid_session_date", "Invalid legacy session date") from exc


def _number(value, field, integer=False):
    try:
        number = Decimal(value)
    except InvalidOperation as exc:
        raise ExchangeDataError("invalid_number", f"Invalid {field}") from exc
    _require(number.is_finite() and (number >= 0 if integer else number > 0),
             "invalid_number", f"{field} must be finite and {'nonnegative' if integer else 'positive'}")
    if integer:
        _require(number == number.to_integral_value(), "invalid_volume", "Volume must count whole traded shares")
        _require(number <= 2**63 - 1, "invalid_volume", "Volume exceeds supported exchange quantity range")
        return int(number)
    result = float(number)
    _require(math.isfinite(result), "invalid_number", f"{field} exceeds finite output range")
    return result


def parse_bhavcopy(content, day, kind="csv", expected_sha256=None):
    """Validate one daily file and return the exact five EQ raw observations."""
    day = _day(day).isoformat()
    observed_hash = hashlib.sha256(content).hexdigest()
    if expected_sha256 is not None:
        _require(isinstance(expected_sha256, str) and bool(re.fullmatch(r"[0-9a-f]{64}", expected_sha256)), "invalid_hash", "Expected SHA-256 must be 64 lowercase hex digits")
        _require(expected_sha256 == observed_hash, "checksum_mismatch", "Source artifact differs from its expected SHA-256")
    payload, member = _csv_payload(content, kind)
    try:
        reader = csv.reader(io.StringIO(payload.decode("utf-8-sig")), strict=True)
        header = [cell.strip() for cell in next(reader, [])]
        # The original NSE legacy format commonly terminates each row with a
        # single trailing comma. Accept that documented empty last field only.
        trailing = bool(header and header[-1] == "")
        if trailing:
            header.pop()
        _require(header and all(header) and len(header) == len(set(header)),
                 "invalid_header", "CSV headers must be nonempty and unique")
        candidates = [name for name, columns in FORMATS.items() if set(columns.values()).issubset(header)]
        _require(len(candidates) == 1, "unknown_schema", "CSV does not match a supported NSE legacy or UDiFF schema")
        provider_format = candidates[0]
        columns = FORMATS[provider_format]
        if provider_format == "udiff":
            _require({"BizDt", "Sgmt", "Src", "FinInstrmTp"}.issubset(header), "unknown_schema", "UDiFF requires business date and NSE cash-market identity fields")
        selected, seen = {}, set()
        count = 0
        symbols = {ticker.removesuffix(".NS"): ticker for ticker in TICKERS}
        for cells in reader:
            _require(bool(cells), "empty_row", "Unexpected empty CSV row")
            if trailing and len(cells) == len(header) + 1 and cells[-1] == "":
                cells.pop()
            _require(len(cells) == len(header), "row_width", "CSV row width differs from its header")
            row = dict(zip(header, (cell.strip() for cell in cells)))
            count += 1
            _require(_session_date(row[columns["date"]], provider_format) == day,
                     "date_mismatch", "Every source row must belong to the explicitly requested session")
            if provider_format == "udiff":
                _require(_session_date(row["BizDt"], provider_format) == day and row["Src"] == "NSE" and row["Sgmt"] == "CM",
                         "market_identity", "UDiFF must describe NSE cash-market data on the requested business date")
            symbol, series = row[columns["symbol"]], row[columns["series"]]
            if symbol not in symbols or series != "EQ":
                continue
            _require(symbol not in seen, "duplicate_security", "More than one EQ observation for a requested security")
            seen.add(symbol)
            if provider_format == "udiff":
                _require(row["FinInstrmTp"] == "STK", "instrument_type", "Selected UDiFF equities must be STK instruments")
            isin = row[columns["isin"]]
            _require(bool(re.fullmatch(r"IN[A-Z0-9]{9}[0-9]", isin)), "invalid_isin", "Selected security needs a structurally valid Indian ISIN")
            values = {key: _number(row[columns[key]], key, integer=(key == "volume"))
                      for key in ("open", "high", "low", "close", "volume")}
            _require(values["low"] <= min(values["open"], values["close"]) <= max(values["open"], values["close"]) <= values["high"],
                     "invalid_ohlc", "Raw OHLC bounds are inconsistent")
            selected[symbols[symbol]] = {"date": day, "ticker": symbols[symbol], "series": "EQ", "isin": isin, **values}
        _require(set(selected) == set(TICKERS), "missing_security", "All five requested tickers need exactly one EQ observation; no missing-value fills")
        _require(len({row["isin"] for row in selected.values()}) == len(TICKERS),
                 "duplicate_isin", "Different requested equities cannot share one reported ISIN")
    except (UnicodeError, csv.Error) as exc:
        raise ExchangeDataError("invalid_csv", "Input is not a supported UTF-8 CSV artifact") from exc
    return {"provider_format": provider_format, "source_rows": count,
            "artifact_sha256": observed_hash, "csv_member": member,
            "csv_sha256": hashlib.sha256(payload).hexdigest(),
            "rows": [selected[ticker] for ticker in TICKERS]}


def write_bundle(content, day, directory, kind="csv", expected_sha256=None, official_fetch=False,
                 requested_format=None, permission_review=None):
    """Exclusively create raw evidence and per-security CSVs; never approve F1."""
    _require(not official_fetch or permission_review is not None, "permission_required", "Official automated acquisition requires its separate permission review identity")
    parsed = parse_bhavcopy(content, day, kind, expected_sha256)
    if requested_format is not None:
        _require(parsed["provider_format"] == requested_format, "format_mismatch", "Downloaded schema differs from the requested official format")
    directory = Path(directory)
    _require(not directory.exists(), "output_exists", "Use a new output directory; existing acquisition evidence is preserved")
    report = {"schema_version": 1, "kind": "nse_raw_acquisition", "status": "raw_only_not_reconciled",
              "date": day, "acquired_at_utc": datetime.now(timezone.utc).isoformat(),
              "provider": "National Stock Exchange of India (declared file format)",
              "lineage": ["nse_india"], "source_url": archive_url(day, parsed["provider_format"]),
              "origin_evidence": "official_https" if official_fetch else "local_file_origin_unverified",
              "currency": "INR", "price_basis": "raw", "adjustment_method": "none; no adjustments applied",
              "rights_status": "unreviewed", "calendar_status": "not_supplied", "corporate_actions_status": "not_supplied",
              "provider_format": parsed["provider_format"], "source_rows": parsed["source_rows"],
              "raw_artifact": {"path": f"source.{kind}", "sha256": parsed["artifact_sha256"]},
              "csv_member": parsed["csv_member"], "csv_sha256": parsed["csv_sha256"],
              "expected_sha256_supplied": expected_sha256 is not None, "files": [],
              "findings": [{"code": "zero_volume", "ticker": row["ticker"], "date": day}
                           for row in parsed["rows"] if row["volume"] == 0],
              "limitations": ["Raw exchange closes are not Yahoo split/dividend-adjusted closes.",
                  "File/schema/TLS checks do not establish source rights, complete calendar, or corporate-action adjustments.",
                  "A local file's official origin and the ticker/ISIN point-in-time mapping require review.",
                  "No fresh experiment is registered or scored and no price is filled, adjusted, or dropped."]}
    if permission_review is not None:
        report["automation_permission_review"] = permission_review
    artifacts = {f"source.{kind}": content}
    for row in parsed["rows"]:
        stream = io.StringIO(newline="")
        writer = csv.DictWriter(stream, fieldnames=list(row))
        writer.writeheader()
        writer.writerow(row)
        filename = row["ticker"].replace(".", "_") + ".csv"
        data = stream.getvalue().encode("utf-8")
        artifacts[filename] = data
        report["files"].append({"ticker": row["ticker"], "path": filename, "sha256": hashlib.sha256(data).hexdigest(),
                                "columns": {"date": "date", "price": "close", "volume": "volume"}})
    # Completion metadata is last. Invalid input never creates an output bundle;
    # a failed filesystem write cannot be mistaken for a completed acquisition.
    artifacts["acquisition.json"] = (json.dumps(report, indent=2, allow_nan=False) + "\n").encode("utf-8")
    directory.mkdir(parents=True, exist_ok=False)
    for filename, data in artifacts.items():
        with (directory / filename).open("xb") as handle:
            handle.write(data)
    return report
