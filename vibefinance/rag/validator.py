from vibefinance.agents.base import Citation, EvidenceClaim
from vibefinance.analysis.financial_facts import extract_financial_facts


def validate_citations(citations: list[Citation], allowed: dict[str, Citation]):
    """Validate passage provenance only, not semantic entailment or truth."""
    valid, rejected = [], []
    for citation in citations:
        source = allowed.get(citation.chunk_id)
        if source is None or any(getattr(citation, field) != getattr(source, field)
                                 for field in ("source_id", "doc_title", "excerpt", "date", "score")):
            rejected.append(citation.chunk_id)
        else:
            valid.append(citation)
    return valid, rejected


def validate_claims(claims: list[EvidenceClaim], allowed: dict[str, Citation], computed_facts=None):
    """Accept exact quotations, reproducible financial templates or approved computations.

    Financial claims must match a template independently re-extracted from each
    attached registered passage. Computed claims require an approved full claim
    regenerated by the caller. This does not prove generic semantic entailment,
    completeness of the analysis, or real-world accuracy of synthetic sources.
    """
    approved = computed_facts or {}
    if not isinstance(approved, dict):
        approved = {claim.claim_id: claim for claim in approved}
    valid, rejected, seen = [], [], set()
    cache = {}
    for claim in claims:
        sources = [allowed.get(chunk_id) for chunk_id in claim.citation_ids]
        accept = bool(claim.text.strip() and sources and all(sources) and claim.claim_id not in seen)
        if accept and claim.method == "quotation":
            accept = claim.fact_key is None and claim.value is None and claim.unit is None
            accept = accept and all(claim.text in source.excerpt for source in sources)
        elif accept and claim.method == "financial_fact":
            for source in sources:
                if source.chunk_id not in cache:
                    cache[source.chunk_id] = extract_financial_facts(source.excerpt)
                accept = accept and any(
                    (claim.fact_key, claim.value, claim.unit, claim.text) ==
                    (fact.key, fact.value, fact.unit, fact.text)
                    for fact in cache[source.chunk_id]
                )
        elif accept and claim.method == "computed":
            expected = approved.get(claim.claim_id)
            if isinstance(expected, dict):
                try:
                    expected = EvidenceClaim.model_validate(expected)
                except (TypeError, ValueError):
                    expected = None
            accept = expected is not None and claim == expected
        elif accept:
            accept = False
        seen.add(claim.claim_id)
        (valid if accept else rejected).append(claim if accept else claim.claim_id)
    return valid, rejected
